def cover_status(e):
    """(발행 가능 여부, 사유). 운영 표지 파일이 있어야 한다(원본 PNG → JPEG 변환본)."""
    own = ROOT / f"assets/covers/{e['id']}.editorial-v3.jpg"
    if not own.is_file():
        return False, f'표지 필요: {own.relative_to(ROOT)}'
    return True, 'ok'


def one_line(t):
    return t.replace('\n', ' ')


def package():
    # 공용 문구(CTA·공통 태그)는 27편과 같은 것을 쓴다 — 두 캠페인의 말투가 갈라지지 않게.
    from codex.campaign27 import CORE_TAGS, IG_CTA, YT_CTA
    for e in EPISODES:
        e['cover_file'] = f"assets/covers/{e['id']}.editorial-v3.jpg"
        e['cover_complete'] = True
        ready, why = cover_status(e)
        e['cover_ready'] = ready
        e['cover_note'] = why
        e['hold'] = not ready
        e['reel_cards'] = list(range(1, len(e['cards']) + 1))
        e['reel'] = {'big': e['hook'].split('\n'), 'badge': e['product'], 'sub': e['series'],
                     'stake': '', 'beats': [c['body'] for c in e['cards']], 'loop': e['question']}
        title = one_line(e['hook'])
        if e['hashtags'][0].lower() not in title.lower():
            title = f"{title} | {e['product']}"
        e['yt_title'] = title[:90]
        tags = e['hashtags'] + [t for t in CORE_TAGS if t not in e['hashtags']]
        e['ig_tags'] = tags[:5]
        ig_tags = ' '.join('#' + t for t in e['ig_tags'])
        yt_tags = ' '.join('#' + t for t in (['Shorts'] + e['ig_tags'][:4]))
        lines = '\n'.join(f"· {c['title']}: {c['figure']}" for c in e['cards'])
        refs = '\n'.join(e['sources'])
        assumed = '가정' in e['assumptions']
        core = (f"[{e['series']}] {one_line(e['hook'])}\n\n{lines}\n\n👉 {one_line(e['verdict_text'])}"
                f"\n\n※ 계산 조건{'(가정 포함)' if assumed else ''}: {e['assumptions']}")
        if refs:
            core += f"\n출처(확인일 {DATE}):\n{refs}"
        e['caption'] = f"{core}\n\n💬 {e['question']}\n{IG_CTA}\n\n{ig_tags}"
        e['youtube_description'] = f"{core}\n\n💬 {e['question']}\n{YT_CTA}\n\n{yt_tags}"
        e['youtube_tags'] = e['ig_tags'] + ['생활비', '절약', '돈 아끼는 법']
        e['threads_tag'] = e['hashtags'][0]
        th = (f"{one_line(e['hook'])}\n\n" + '\n'.join(f"· {c['title']}: {c['figure']}" for c in e['cards'])
              + f"\n\n{one_line(e['verdict_text'])}\n\n※ {'가정 포함 계산' if assumed else '조건'}: {e['assumptions']}")
        tail = f"\n\n{e['question']} 답글로 알려줘."
        if len(th) + len(tail) > 500:
            th = th[:500 - len(tail) - 1].rstrip() + '…'
        e['threads_text'] = th + tail
        e['threads_chain'] = []
        e['cta'] = {
            'instagram': dict(screen='좋아요 + 팔로우',
                              narration=f"{e['question']} 도움 됐으면 좋아요 누르고, 매일 올라오는 돈 계산 받아 보려면 팔로우 해 둬."),
            'youtube': dict(screen='좋아요 + 구독',
                            narration=f"{e['question']} 도움 됐으면 좋아요 누르고, 매일 올라오는 돈 계산 받아 보려면 구독 해 둬."),
        }
    return {'schema_version': 2, 'brand': '돈값하나', 'handle': '@dongabhana', 'as_of': DATE,
            'start': START, 'items': EPISODES}


if __name__ == '__main__':
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'build' / 'campaign30.json'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(package(), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{len(EPISODES)} episodes -> {dest}')
