IG_CTA = '도움 됐으면 좋아요 ❤️ 매일 하나씩 생활 속 돈 계산 올려요. 놓치기 싫으면 팔로우!'
YT_CTA = '도움 됐으면 좋아요 👍 매일 하나씩 생활 속 돈 계산 올려요. 다음 편 받아 보려면 구독!'


def one_line(t):
    return t.replace('\n', ' ')

def package():
    for e in EPISODES:
        x = EXTRA[e['id'].split('-',1)[1]]
        e['cover_file'] = f"assets/covers/{e['cover']}" + ('.jpg' if 'photo-' in e['cover'] else '.editorial-v3.jpg')
        replacement = f"assets/covers/{e['id']}.editorial-v3.jpg"
        if (ROOT/replacement).exists(): e['cover_file'] = replacement
        ready, why = cover_status(e)
        e['cover_ready'] = ready
        e['cover_note'] = why
        # hold 는 이제 '표지 대기' 뜻 하나다. 표지가 준비된 편은 순서대로 발행된다.
        e['hold'] = not ready
        e['hashtags'] = x['tags'].split()
        e['key'] = dict(label=x['key'][0], figure=x['key'][1])
        e['reel_cards'] = list(range(1, len(e['cards'])+1))
        e['reel'] = {'big':e['hook'].split('\n'), 'badge':e['product'],
                     'sub':'', 'stake':'', 'beats':[c['body'] for c in e['cards']], 'loop':e['question']}
        # 유튜브 제목은 검색어가 앞 40자 안에 들어가야 한다. 훅에 주제어가 없으면 편 이름을 붙인다.
        title = one_line(e['hook'])
        if e['hashtags'][0].lower().replace('패스','') not in title.lower():
            title = f"{title} | {e['product']}"
        e['yt_title'] = title[:90]
        tags = e['hashtags'] + [t for t in CORE_TAGS if t not in e['hashtags']]
        e['ig_tags'] = tags[:5]
        ig_tags = ' '.join('#'+t for t in e['ig_tags'])
        yt_tags = ' '.join('#'+t for t in (['Shorts'] + e['ig_tags'][:4]))
        # 캡션은 첫 줄(훅)에서 멈춰도 뜻이 통하고, 펼치면 핵심 숫자 4줄 → 결론 → 조건 순.
        lines = '\n'.join(f"· {c['title']}: {c['figure']}" for c in e['cards'])
        refs = '\n'.join(e['sources'])
        core = (f"{one_line(e['hook'])}\n\n{lines}\n\n👉 {one_line(e['verdict_text'])}"
                f"\n\n※ 계산 조건{'(가정 포함)' if '가정' in e['assumptions'] else ''}: {e['assumptions']}")
        if refs: core += f"\n출처(기준일 {DATE}):\n{refs}"
        e['caption'] = f"{core}\n\n💬 {e['question']}\n{IG_CTA}\n\n{ig_tags}"
        e['youtube_description'] = f"{core}\n\n💬 {e['question']}\n{YT_CTA}\n\n{yt_tags}"
        e['youtube_tags'] = e['ig_tags'] + ['생활비', '절약', '돈 아끼는 법']
        e['threads_tag'] = e['hashtags'][0]
        th = (f"{one_line(e['hook'])}\n\n"+'\n'.join(f"· {c['title']}: {c['figure']}" for c in e['cards'])
              + f"\n\n{one_line(e['verdict_text'])}\n\n※ {'가정 포함 계산' if '가정' in e['assumptions'] else '계산 기준'}: {e['assumptions']}")
        tail = f"\n\n{e['question']} 답글로 알려줘."
        if len(th) + len(tail) > 500:
            th = th[:500-len(tail)-1].rstrip() + '…'
        e['threads_text'] = th + tail
        e['threads_chain'] = []
        e['narration'] = list(x['narr'])
        e['cta'] = {
            'instagram': dict(screen='좋아요 + 팔로우',
                              narration=f"{e['question']} 도움 됐으면 좋아요 누르고, 매일 올라오는 돈 계산 받아 보려면 팔로우 해 둬."),
            'youtube': dict(screen='좋아요 + 구독',
                            narration=f"{e['question']} 도움 됐으면 좋아요 누르고, 매일 올라오는 돈 계산 받아 보려면 구독 해 둬."),
        }
    return {'schema_version':2,'brand':'돈값하나','handle':'@dongabhana','as_of':DATE,'items':EPISODES}

if __name__ == '__main__':
    # 검토용 사본. 발행·렌더는 이 파일(package())을 직접 읽으므로 사본은 저장소에 두지 않는다.
    dest=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'build'/'campaign27.json'
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(json.dumps(package(),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'{len(EPISODES)} episodes -> {dest}')
