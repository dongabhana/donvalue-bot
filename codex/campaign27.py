def package():
    for e in EPISODES:
        e['cover_file'] = f"assets/covers/{e['cover']}" + ('.jpg' if 'photo-' in e['cover'] else '.editorial-v3.jpg')
        replacement = f"assets/covers/{e['id']}.editorial-v3.jpg"
        if (ROOT/replacement).exists(): e['cover_file'] = replacement
        e['reel_cards'] = list(range(1, len(e['cards'])+1))
        e['reel'] = {'big':e['hook'].split('\n'), 'badge':e['product'],
                     'sub':'', 'stake':'', 'beats':[c['body'] for c in e['cards']], 'loop':e['question']}
        e['yt_title'] = e['hook'].replace('\n',' ')+' #Shorts'
        summary = '\n'.join(f"{c['title']}: {c['figure']}\n{c['body']}" for c in e['cards'])
        refs = '\n'.join(e['sources'])
        core = f"{e['hook'].replace(chr(10),' ')}\n\n{summary}\n\n{e['verdict_text'].replace(chr(10),' ')}\n\n※ {e['assumptions']}"
        if refs: core += f'\n기준일: {DATE}\n출처:\n{refs}'
        tags = ' '.join('#'+t for t in e['hashtags'])
        e['caption'] = core+f"\n\n{e['question']}\n돈값하나 · 도움 됐으면 좋아요, 다음 돈 계산은 팔로우!\n\n{tags}"
        e['youtube_description'] = core+f"\n\n{e['question']}\n돈값하나 · 도움 됐으면 좋아요, 다음 돈 계산은 구독!\n\n#Shorts {tags}"
        e['threads_text'] = f"{e['hook'].replace(chr(10),' ')}\n\n"+'\n'.join(f"{c['title']}: {c['figure']}." for c in e['cards'])+f"\n\n{e['verdict_text'].replace(chr(10),' ')}\n※ {e['assumptions']}\n\n{e['question']}"
        e['threads_chain'] = []
        e['narration'] = [e['hook'].replace('\n',' ')+'.']+[c['body'] for c in e['cards']]+[e['verdict_text'].replace('\n',' ')]
        e['cta'] = {p:dict(screen='좋아요 + '+word, narration=e['question']+' 도움 됐으면 좋아요, 다음 돈 계산도 궁금하면 '+word+' 해 둬.') for p,word in [('instagram','팔로우'),('youtube','구독')]}
    return {'schema_version':1,'brand':'돈값하나','handle':'@dongabhana','as_of':DATE,'items':EPISODES}

if __name__ == '__main__':
    dest=ROOT/'content'/'campaign27.json'
    dest.write_text(json.dumps(package(),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'{len(EPISODES)} episodes -> {dest}')
