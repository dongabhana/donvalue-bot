def cover_status(e):
    """(발행 가능 여부, 사유). 새 표지가 필요한 편은 편 전용 새 파일이 있어야 한다."""
    import hashlib
    own = ROOT/f"assets/covers/{e['id']}.editorial-v3.jpg"
    if e['order'] not in NEW_COVER_NEEDED:
        return (ROOT/e['cover_file']).is_file(), 'ok'
    if not own.is_file():
        return False, f'새 표지 필요: {own.relative_to(ROOT)}'
    if hashlib.sha256(own.read_bytes()).hexdigest() in REJECTED_COVER_SHA:
        return False, f'반려된 표지 그대로: {own.relative_to(ROOT)}'
    return True, 'ok'

