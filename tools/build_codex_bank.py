def balanced_cases():
    buckets = defaultdict(list)
    for row in CASES:
        buckets[row['category']].append(row)
    result = []
    while any(buckets.values()):
        for category in CATEGORIES:
            if buckets[category]:
                result.append(buckets[category].pop(0))
    return result


